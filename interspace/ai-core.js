  function train(){
    MARKOV.table = {}; MARKOV.starters = [];
    for(const line of CORPUS){
      const t = tokenize(line);
      if(t.length < 2) continue;
      MARKOV.starters.push(t[0]);
      for(let i = 0; i < t.length - MARKOV.order; i++){
        const key = t.slice(i, i + MARKOV.order).join(' ');
        const next = t[i + MARKOV.order];
        (MARKOV.table[key] = MARKOV.table[key] || []).push(next);
      }
      const lastKey = t.slice(-MARKOV.order).join(' ');
      if(!MARKOV.table[lastKey]) MARKOV.table[lastKey] = [];
    }
  }

  const pick   = a => a[Math.floor(Math.random()*a.length)];
  const chance = p => Math.random() < p;

  function markovGenerate(maxWords = 12, seed = null){
    let start = seed && MARKOV.starters.includes(seed) ? seed : pick(MARKOV.starters);
    let startKey = null;
    for(const k of Object.keys(MARKOV.table)){
      if(k.startsWith(start + ' ')){ startKey = k; break; }
    }
    if(!startKey) startKey = pick(Object.keys(MARKOV.table));
    let words = startKey.split(' ');
    for(let i = 0; i < maxWords; i++){
      const key = words.slice(-MARKOV.order).join(' ');
      const nexts = MARKOV.table[key];
      if(!nexts || !nexts.length) break;
      words.push(pick(nexts));
      if(chance(0.2) && words.length >= 5) break;
    }
    return polish(words.join(' '));
  }
  function polish(str){
    str = str.replace(/\s+([.,!?;:])/g, '$1').replace(/\s+/g, ' ').trim();
    if(!str) return '';
    str = str[0].toUpperCase() + str.slice(1);
    if(!/[.!?]$/.test(str)) str += '.';
    return str;
  }
